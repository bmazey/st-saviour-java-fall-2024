public abstract class Car {


    private String license;
    private int speed;
 
 
    public String getLicense() {
        return this.license;
    }
 
 
    public void setLicense(String license) {
        this.license = license;
    }
 
 
    public int getSpeed() {
        return this.speed;
    }
 
 
    public void setSpeed(int speed) {
        this.speed = speed;
    }
 }
 